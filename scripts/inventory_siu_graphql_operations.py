#!/usr/bin/env python3
"""Inventory GraphQL operations embedded in publicly served SIU JavaScript bundles.

Static analysis only: never executes discovered queries, mutations or subscriptions.
"""
import argparse
import collections
import datetime
import hashlib
import json
import re
import urllib.parse
import urllib.request
from html.parser import HTMLParser
from pathlib import Path

PAGE = "https://siu.ambq.gov.co/siu/schedule-mng/schedules"
ORIGIN = "https://siu.ambq.gov.co"
OUT = Path("build/siu-graphql-operations")
MAX_BUNDLES = 160
MAX_BYTES = 12_000_000
OP = re.compile(r"\\b(query|mutation|subscription)\\s+([A-Za-z_][A-Za-z_0-9]*)\\s*(?:\\([^{}]{0,3000}\\))?\\s*\\{")
GQL = re.compile(r"\\b(?:gql|graphql)\\s*`([^`]{1,25000})`", re.S)
CHUNK = re.compile(r'(?:(?:static/js/)?[A-Za-z0-9_.-]+\\.chunk\\.js|(?:static/js/)?(?:main|runtime-main)\\.[A-Za-z0-9_.-]+\\.js)')
SCRIPT = re.compile(r'<script[^>]+src=["\\\']([^"\\\']+\\.js(?:\\?[^"\\\']*)?)', re.I)
SENSITIVE = re.compile(r"token|secret|authorization|cookie|password|key", re.I)

def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (compatible; SIU-static-research/1.0)"})
    with urllib.request.urlopen(req, timeout=35) as response:
        content = response.read(MAX_BYTES + 1)
        if len(content) > MAX_BYTES:
            raise ValueError("bundle exceeds size limit")
        return content.decode("utf-8", errors="replace")

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--max-bundles",type=int,default=MAX_BUNDLES)
    args=p.parse_args()
    OUT.mkdir(parents=True,exist_ok=True)
    html=fetch(PAGE)
    candidates=set(SCRIPT.findall(html))
    candidates.update(CHUNK.findall(html))
    # Inspect runtime/main bundles first: webpack often lists the numbered chunk hashes there.
    queue=collections.deque(sorted(candidates, key=lambda x: ("runtime" not in x and "main" not in x, x)))
    visited=set()
    found={}
    bundle_report=[]
    while queue and len(visited)<max(1,min(args.max_bundles,MAX_BUNDLES)):
        item=queue.popleft()
        url=urllib.parse.urljoin(ORIGIN+"/siu/",item)
        if urllib.parse.urlsplit(url).netloc!="siu.ambq.gov.co":
            continue
        if url in visited:continue
        visited.add(url)
        try:
            js=fetch(url)
        except Exception as exc:
            bundle_report.append({"url":url,"error":type(exc).__name__})
            continue
        sha=hashlib.sha256(js.encode()).hexdigest()
        matches=[]
        # Extract only operation names and types; no arguments, tokens, or response data.
        for match in OP.finditer(js):
            typ,name=match.group(1),match.group(2)
            matches.append({"type":typ,"name":name})
            found.setdefault((typ,name),set()).add(url)
        bundle_report.append({"url":url,"sha256":sha,"bytes":len(js),"operation_occurrences":len(matches)})
        for candidate in CHUNK.findall(js):
            if candidate.startswith("static/js/"):
                path=candidate
            else:
                path="static/js/"+candidate
            next_url=urllib.parse.urljoin(ORIGIN+"/siu/",path)
            if next_url not in visited:
                queue.append(path)
        # CRA webpack runtime commonly encodes chunk IDs and hash maps rather than filenames.
        # Record this limitation instead of guessing chunk URLs.
    ops=[{"type":t,"name":n,"bundles":sorted(urls)} for (t,n),urls in sorted(found.items())]
    result={"source":PAGE,"timestamp_utc":datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "analysis":"Static JS only; no GraphQL operations executed",
            "bundles_checked":len(visited),"operations":ops,"bundles":bundle_report,
            "limitations":["Webpack chunk maps may use numeric IDs and computed filenames; inventory is not guaranteed exhaustive.",
                           "Regex matches require review for false positives; absence does not prove an operation is unavailable."]}
    (OUT/"operations.json").write_text(json.dumps(result,indent=2,ensure_ascii=False)+"\n")
    lines=["# SIU GraphQL operations found in public JavaScript bundles","",
           f"Bundles attempted: {len(visited)}; unique named operations: {len(ops)}","",
           "| Type | Operation | Bundles |","|---|---|---:|"]
    lines.extend(f"| {x['type']} | \`{x['name']}\` | {len(x['bundles'])} |" for x in ops)
    lines.extend(["","## Notes","","Static extraction only. No discovered operation has been invoked by this workflow.",
                  "Some chunks may be lazy-loaded or generated by Webpack numeric chunk maps; inspect the bundle report for coverage."])
    (OUT/"report.md").write_text("\n".join(lines)+"\n")
    print(json.dumps({"bundles_attempted":len(visited),"operations_found":len(ops),"operations":ops},ensure_ascii=False))
if __name__=="__main__":main()
